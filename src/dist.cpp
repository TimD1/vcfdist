/**
 * @brief Calculates the NG50 statistic from a list of phase block sizes and genome size.
 *
 * @param[in] phase_blocks List of phase block sizes.
 * @param[in] total_bases Sum total of all bases in the genome.
 * @return The minimum value for which the sum of phase blocks greater than this size account for
 *   more than 50% of total genome size, or 0 if less than 50% of the genome is phased.
 */
int calc_ng50(std::vector<int> phase_blocks, size_t total_bases) {
    size_t total_phased = 0;
    // sort blocks in descending order
    std::sort(phase_blocks.begin(), phase_blocks.end(), std::greater<>());
    // calculate running sum, return once 50% of genome size is reached
    for (size_t i = 0; i < phase_blocks.size(); i++) {
        total_phased += phase_blocks[i];
        if (total_phased >= double(total_bases) / 2)
            return phase_blocks[i];
    }
    return 0;
}

