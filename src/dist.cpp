/**
 * @brief Constructs alignment graph from supercluster variants and reference sequence.
 *
 * Builds a DAG where query nodes represent all variant and reference paths, and truth
 * nodes represent the selected truth haplotype path as a truth DAG: each truth variant node
 * is paired with a parallel reference-allele bypass node (tskips[tni] set to the bypassed
 * variant's index) offering an alternate, tolled route past that variant, with reference end
 * coordinates (tends) recorded for every truth node and connectivity set between adjacent nodes.
 *
 * Node 0 of each side is always a reference node, which is what lets calc_prec_recall_aln() seed
 * its search at a fixed origin cell. Away from the contig start that node is the one-base left
 * flank; at reference position 0, where no base lies to the left, a synthetic zero-width reference
 * node stands in for it so that a variant's parallel allele still has a predecessor.
 *
 * Every node's coordinate span equals the length of the sequence it holds, with zero-width insertion
 * variant and bypass nodes the deliberate exception. The reference window is clamped at the contig
 * end to keep that true of the trailing node, which is otherwise the one place where the coordinate
 * and the sequence could disagree; at a contig end it becomes a zero-width sink.
 *
 * @param[in] sc Supercluster data containing query and truth variant containers.
 * @param[in] sc_idx Supercluster index in the contig.
 * @param[in] ref Reference FASTA data.
 * @param[in] ctg Contig name.
 * @param[in] truth_hap Truth haplotype index (0 or 1).
 * @throws ERROR if a reference contig is not found in the FASTA.
 */
Graph::Graph(
		std::shared_ptr<ctgSuperclusters> sc, int sc_idx,
        std::shared_ptr<fastaData> ref, const std::string & ctg, hap_t truth_hap) {

    ////////////////////////////////
    // STEP 1: CREATE QUERY NODES //
    ////////////////////////////////

    // initialize helper variables
    std::shared_ptr<ctgVariants> qvars = sc->callset_vars[QUERY];
    std::shared_ptr<ctgVariants> tvars = sc->callset_vars[TRUTH];
    int qvar_beg = std::distance(qvars->superclusters.begin(),
            std::lower_bound(qvars->superclusters.begin(), qvars->superclusters.end(), sc_idx));
    int qvar_end = std::distance(qvars->superclusters.begin(),
            std::upper_bound(qvars->superclusters.begin(), qvars->superclusters.end(), sc_idx));
    int tvar_beg = std::distance(tvars->superclusters.begin(),
            std::lower_bound(tvars->superclusters.begin(), tvars->superclusters.end(), sc_idx));
    int tvar_end = std::distance(tvars->superclusters.begin(),
            std::upper_bound(tvars->superclusters.begin(), tvars->superclusters.end(), sc_idx));
    int ref_beg = sc->get_min_ref_pos(qvar_beg, qvar_end, tvar_beg, tvar_end);
    int ref_end = sc->get_max_ref_pos(qvar_beg, qvar_end, tvar_beg, tvar_end);
    // exclusive end of the reference window every node draws its sequence from. It reaches one past
    // ref_end, giving the window a right flank as ref_beg = min_pos - 1 gives it a left one, and is
    // clamped at the contig end so that a node's coordinate span never exceeds the sequence
    // substr() hands it -- the mirror of ref_beg clamping at position 0 (#189)
    const int win_end = std::min(ref_end + 1, int(ref->fasta.at(ctg).size()));

    int ref_pos = ref_beg;
    this->sc = sc;
    this->sc_idx = sc_idx;
    // keep track of all node ends. variants are already sorted in order of their starts, but
    // to create the correct reference substrings we need to know where the next end is too
    std::priority_queue<int, std::vector<int>, std::greater<int> > qnode_ends;

    // iterate through all the variants
    this->qnodes = 0;
    for (int var_idx = qvar_beg; var_idx < qvar_end; var_idx++) {
        // skip variants that we've already evaluated
        if (qvars->errtypes[truth_hap][var_idx] != ERRTYPE_UN) { continue; }
        
        // prior to adding the next variant, add as many reference nodes as necessary
        // due to earlier variants that end before it starts
        int var_pos = qvars->poss[var_idx];
        while (ref_pos < var_pos) {
            // get length of this reference segment
            int next_ref_pos; 
            if (!qnode_ends.empty() && qnode_ends.top() < var_pos) { // prev var ends before next starts
                next_ref_pos = qnode_ends.top();
                // multiple vars may end at same location; remove all from node_ends
                while (!qnode_ends.empty() && qnode_ends.top() == next_ref_pos) qnode_ends.pop();
            } else {
                next_ref_pos = var_pos;
            }
            // add reference node
            assert(next_ref_pos <= var_pos);
            this->qnodes++;
            this->qseqs.push_back("_" + ref->fasta.at(ctg).substr(ref_pos, next_ref_pos-ref_pos));
            this->qbegs.push_back(ref_pos - ref_beg);
            this->qends.push_back(next_ref_pos - ref_beg);
            this->qtypes.push_back(TYPE_REF);
            this->qidxs.push_back(-1);
            ref_pos = next_ref_pos;
        }

        // At position 0 there is no base to the left, so the one-base left flank node that would
        // otherwise open the graph cannot exist and this variant node would become node 0 -- the
        // hardcoded origin of calc_prec_recall_aln(), leaving its parallel reference allele with no
        // predecessor and unreachable. A zero-width reference node supplies the origin cell the
        // aligner needs; its sentinel is all the flank node ever contributed there (#177). No
        // position test is needed: ref_beg = max(0, min_pos - 1), so a side reaches its first
        // variant with nothing emitted only when ref_pos == var_pos == ref_beg == 0.
        if (this->qnodes == 0) {
            this->qnodes++;
            this->qseqs.push_back("_");
            this->qbegs.push_back(0);
            this->qends.push_back(0);
            this->qtypes.push_back(TYPE_REF);
            this->qidxs.push_back(-1);
        }

        // add the variant
        assert(ref_pos == var_pos);
        this->qnodes++;
        this->qseqs.push_back("_" + qvars->alts[var_idx]);
        this->qbegs.push_back(qvars->poss[var_idx] - ref_beg);
        this->qends.push_back(qvars->poss[var_idx] + qvars->rlens[var_idx] - ref_beg);
        this->qtypes.push_back(qvars->types[var_idx]);
        this->qidxs.push_back(var_idx);
        if (qvars->rlens[var_idx]) 
            qnode_ends.push(qvars->poss[var_idx] + qvars->rlens[var_idx]);
    }

    // all variants added, add the remainder of the reference
    while (ref_pos < ref_end) {
        // get the length of this reference segment
        int next_ref_pos;
        bool last_segment = false;
        if (!qnode_ends.empty() && qnode_ends.top() < ref_end) { // stop at variant end
            next_ref_pos = qnode_ends.top();
            // multiple vars may end at same location; remove all from node_ends
            while (!qnode_ends.empty() && qnode_ends.top() == next_ref_pos) qnode_ends.pop();
        } else {
            next_ref_pos = win_end; // add remainder of reference in this supercluster
            // at a contig end win_end can equal ref_pos, leaving this trailing node zero-width and
            // the loop condition still true, so close the loop here rather than on ref_pos
            last_segment = true;
        }
        this->qnodes++;
        this->qseqs.push_back("_" + ref->fasta.at(ctg).substr(ref_pos, next_ref_pos-ref_pos));
        this->qbegs.push_back(ref_pos - ref_beg);
        this->qends.push_back(next_ref_pos - ref_beg);
        this->qtypes.push_back(TYPE_REF);
        this->qidxs.push_back(-1);
        ref_pos = next_ref_pos;
        if (last_segment) break;
    }

    /////////////////////////////////////
    // STEP 2: SET QUERY NODE POINTERS //
    /////////////////////////////////////
    this->qprevs.resize(this->qnodes);
    this->qnexts.resize(this->qnodes);

    for (int n1 = 0; n1 < this->qnodes; n1++) {
        for (int n2 = 0; n2 < this->qnodes; n2++) {
            if (n2 == n1) continue; // don't compare node to itself
            // add predecessor of current node
            if (this->qbegs[n1] == this->qends[n2] && n2 < n1)
                this->qprevs[n1].push_back(n2);
            // add successor of current node
            if (this->qends[n1] == this->qbegs[n2] && n1 < n2)
                this->qnexts[n1].push_back(n2);
        }
    }

    ////////////////////////////////
    // STEP 3: CREATE TRUTH NODES //
    ////////////////////////////////

    // iterate through all the variants
    ref_pos = ref_beg;
    this->tnodes = 0;
    this->truth = "";
    for (int var_idx = tvar_beg; var_idx < tvar_end; var_idx++) {
        // skip variants that we've already evaluated
        if (tvars->errtypes[truth_hap][var_idx] != ERRTYPE_UN) { continue; }

        if (tvars->var_on_hap(var_idx, truth_hap)) { // ignore variant if on other hap
            // add reference node before next truth variant
            int var_pos = tvars->poss[var_idx];
            if (var_pos > ref_pos) {
                this->tnodes++;
                this->tseqs.push_back("_" + ref->fasta.at(ctg).substr(ref_pos, var_pos-ref_pos));
                this->tbegs.push_back(ref_pos - ref_beg);
                this->tends.push_back(var_pos - ref_beg);
                this->ttypes.push_back(TYPE_REF);
                this->tidxs.push_back(-1);
                this->tskips.push_back(-1);
                this->truth += ref->fasta.at(ctg).substr(ref_pos, var_pos-ref_pos);
            }

            // no left flank can exist at position 0, so keep node 0 a reference node for the
            // aligner's origin; see the query-side counterpart in STEP 1 (#177)
            if (this->tnodes == 0) {
                this->tnodes++;
                this->tseqs.push_back("_");
                this->tbegs.push_back(0);
                this->tends.push_back(0);
                this->ttypes.push_back(TYPE_REF);
                this->tidxs.push_back(-1);
                this->tskips.push_back(-1);
            }

            // add the truth variant
            this->tnodes++;
            this->tseqs.push_back("_" + tvars->alts[var_idx]);
            int tvar_rlen = tvars->rlens[var_idx];
            this->tbegs.push_back(var_pos - ref_beg);
            this->tends.push_back(var_pos + tvar_rlen - ref_beg);
            this->ttypes.push_back(tvars->types[var_idx]);
            this->tidxs.push_back(var_idx);
            this->tskips.push_back(-1);
            this->truth += tvars->alts[var_idx];

            // parallel reference-allele bypass node (declares this truth variant FN if taken)
            this->tnodes++;
            this->tseqs.push_back("_" + ref->fasta.at(ctg).substr(var_pos, tvar_rlen));
            this->tbegs.push_back(var_pos - ref_beg);
            this->tends.push_back(var_pos + tvar_rlen - ref_beg);
            this->ttypes.push_back(TYPE_REF);
            this->tidxs.push_back(-1);
            this->tskips.push_back(var_idx);

            ref_pos = tvars->poss[var_idx] + tvars->rlens[var_idx];
        }
    }

    // add the remainder of the truth. At a contig end win_end can equal ref_pos, leaving this a
    // zero-width sink node; it stays the node both alleles converge on, and the insertion-leap rule
    // below cannot mistake it for an insertion because it is neither a variant nor a bypass node
    this->tnodes++;
    this->tseqs.push_back("_" + ref->fasta.at(ctg).substr(ref_pos, win_end - ref_pos));
    this->tbegs.push_back(ref_pos - ref_beg);
    this->tends.push_back(win_end - ref_beg);
    this->ttypes.push_back(TYPE_REF);
    this->tidxs.push_back(-1);
    this->tskips.push_back(-1);
    this->truth += ref->fasta.at(ctg).substr(ref_pos, win_end - ref_pos);

    /////////////////////////////////////
    // STEP 4: SET TRUTH NODE POINTERS //
    /////////////////////////////////////

    this->tprevs.resize(this->tnodes);
    this->tnexts.resize(this->tnodes);

    // coordinates hosting a zero-width truth insertion variant node; a direct ref->ref edge
    // across such a locus would give a free (cost-0) path skipping both the alt (variant) and
    // the tolled bypass node, circumventing the bypass toll and mislabeling matched insertions FN
    std::unordered_set<int> insertion_coords;
    for (int tn = 0; tn < this->tnodes; tn++)
        if (this->tidxs[tn] >= 0 && this->tbegs[tn] == this->tends[tn])
            insertion_coords.insert(this->tbegs[tn]);

    for (int n1 = 0; n1 < this->tnodes; n1++) {
        for (int n2 = 0; n2 < this->tnodes; n2++) {
            if (n2 == n1) continue;
            // a variant node and its own bypass node are parallel alternatives, never
            // sequential; skip wiring them together (matters for zero-width insertions,
            // where variant and bypass share tbegs == tends)
            if (this->tskips[n2] >= 0 && this->tskips[n2] == this->tidxs[n1]) continue;
            if (this->tskips[n1] >= 0 && this->tskips[n1] == this->tidxs[n2]) continue;
            // suppress any edge that leaps a zero-width insertion locus, forcing the path through
            // the insertion's variant node (TP) or its tolled bypass node (FN). An edge joining two
            // nodes at coordinate p leaps the insertion unless one endpoint IS the insertion's own
            // alt/bypass node, in which case the edge routes into or out of the insertion rather
            // than past it. Such an endpoint is exactly a zero-width variant or bypass node; testing
            // for that (rather than the old both-ref rule) also closes the leap when the insertion
            // abuts another variant, whose alt/bypass node is reference-spanning but not a plain ref
            // node, and keeps a zero-width node that is neither (the contig-start entry node of
            // STEP 1/STEP 3) from exempting an edge that really does leap the insertion.
            bool n1_ins_node = this->tbegs[n1] == this->tends[n1] &&
                    (this->tidxs[n1] >= 0 || this->tskips[n1] >= 0);
            bool n2_ins_node = this->tbegs[n2] == this->tends[n2] &&
                    (this->tidxs[n2] >= 0 || this->tskips[n2] >= 0);
            bool leaps_insertion = !n1_ins_node && !n2_ins_node;
            if (this->tbegs[n1] == this->tends[n2] && n2 < n1 &&
                    !(leaps_insertion && insertion_coords.count(this->tbegs[n1])))
                this->tprevs[n1].push_back(n2);
            if (this->tends[n1] == this->tbegs[n2] && n1 < n2 &&
                    !(leaps_insertion && insertion_coords.count(this->tends[n1])))
                this->tnexts[n1].push_back(n2);
        }
    }

    this->ref = ref->fasta.at(ctg).substr(ref_beg, win_end - ref_beg);
}

