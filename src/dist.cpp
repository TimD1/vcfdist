/**
 * @brief Generates a haplotype sequence by applying a range of variants to the reference.
 *
 * @param[in] ref A pointer to an object containing the reference sequence.
 * @param[in] vars A pointer to the variants on this contig.
 * @param[in] ctg The name of the current contig.
 * @param[in] beg_idx The 0-based inclusive index of the first variant to include.
 * @param[in] end_idx The 0-based exclusive index of the last variant to include.
 * @param[in] beg_pos The 0-based inclusive index of the first reference base to include.
 * @param[in] end_pos The 0-based exclusive index of the last reference base to include.
 * @param[in] min_qual Skip variants with quality scores below this threshold.
 * @return The sequence generated by applying the selected variants to the reference sequence.
 * @throws ERROR if the next reference segment ends before the current reference position.
 * @throws ERROR if the contig is not present in the reference FASTA.
 * @throws ERROR if the reference position lies outside the contig.
 */
std::string generate_str(
        std::shared_ptr<fastaData> ref, 
        std::shared_ptr<ctgVariants> vars, const std::string & ctg,
        int beg_idx, int end_idx, int beg_pos, int end_pos, 
        int min_qual /* = 0 */) {

    int var_idx = beg_idx;
    std::string str = "";
    while (var_idx < vars->n && vars->poss[var_idx] < beg_pos) var_idx++;
    for (int ref_pos = beg_pos; ref_pos < end_pos; ) {

        // VARIANT
        if (var_idx < end_idx && ref_pos == vars->poss[var_idx]) {
            if (vars->var_quals[var_idx] >= min_qual) {
                switch (vars->types[var_idx]) {
                    case TYPE_INS:
                        str += vars->alts[var_idx];
                        break;
                    case TYPE_DEL:
                        ref_pos += vars->refs[var_idx].size();
                        break;
                    case TYPE_SUB:
                        str += vars->alts[var_idx];
                        ref_pos++;
                        break;
                    case TYPE_CPX:
                        str += vars->alts[var_idx];
                        ref_pos += vars->refs[var_idx].size();
                        break;
                    case TYPE_REF: // not a stored variant type, so nothing to consume
                        break;
                }
            }
            var_idx++; // next variant

        } else { // NO VARIANT
            // add entire ref seq up to next variant or region end
            int ref_end = (var_idx < end_idx) ?
                std::min(end_pos, vars->poss[var_idx]) : end_pos;
            if (ref_end < ref_pos) {
                printf("ref_pos:%d ref_end:%d beg_pos: %d end_pos: %d\n",
                        ref_pos, ref_end, beg_pos, end_pos);
                for(int i = beg_idx; i < end_idx; i++) {
                    printf("%s:%d %s -> %s\n", ctg.data(), vars->poss[i],
                            vars->refs[i].data(), vars->alts[i].data());
                }
                ERROR("No variant, but ref_end < ref_pos (generate_str)");
            }
            // check both failure modes separately, so neither is reported as the other (#167)
            if (ref->fasta.find(ctg) == ref->fasta.end())
                ERROR("Contig '%s' not in reference FASTA (generate_str)", ctg.data());
            const std::string & ref_seq = ref->fasta.at(ctg);
            if (ref_pos < 0 || ref_pos > int(ref_seq.size()))
                ERROR("Position %d out of range on contig '%s' of length %d (generate_str)",
                        ref_pos, ctg.data(), int(ref_seq.size()));
            str += ref_seq.substr(ref_pos, ref_end-ref_pos);
            ref_pos = ref_end;
        }
    }
    return str;
}

